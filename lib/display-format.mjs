// 화면에 날짜를 어떻게 찍는지 정하는 단일 출처.
//
// 이 규칙이 app/page.tsx 안에만 있던 동안, 회귀 테스트는 화면이 "2026.09.06"으로
// 찍는 날짜를 "2026-09-06"이라는 원본 문자열로 찾았다. 문서 어딘가에 그 원본이
// 함께 있는 날에는 느슨한 정규식이 우연히 걸려 통과했고, 없는 날에만 깨졌다.
// 화면과 테스트가 같은 함수를 부르게 해서 그 우연을 없앤다.

/**
 * 화면 표기용 날짜 문자열. 2026-09-06 → 2026.09.06
 *
 * @param {string} date
 * @returns {string}
 */
export function formatDate(date) {
  return date.replaceAll("-", ".");
}
